/**
 * 스플래쉬 동작 값. **아직 확정된 값이 하나도 없어서 전부 비어 있다.**
 *
 * 화면(마크업·색·애니메이션)은 시안에서 다 나왔지만 동작은 그렇지 않다. 기능명세서 FN-B01-03은
 * "세션 확인 동안 스플래시 노출"까지만 정하고 시간을 정하지 않았고, 시안 「후보2」(로딩 지연)도
 * 프레임 이름이 후보라 확정안이 아니다. 그래서 임의의 숫자를 화면 코드에 박지 않고 여기 모은다.
 *
 * 값이 정해지면 이 파일만 채우고 배선한다. 배선 지점은 로그인 화면(B-01)이다.
 *   유효 세션  → 홈(B-03)으로 이동      (BR-B01-03-01)
 *   무효 세션  → 오류 안내 없이 B-01    (FN-B01-03 실패 처리)
 *
 * 순수한 연출 시간(진행바가 차오르는 속도, 점 3개가 튀는 주기)은 여기 없다. 그쪽은 화면 값이라
 * `src/app/animations.css`가 갖는다.
 */

/**
 * 기본 스플래쉬에서 「로딩 지연」 화면으로 바꾸는 기준 시간(ms).
 *
 * `null`이면 전환하지 않는다. 기능명세서 전체에 기준값이 없고 팀에서도 정한 적이 없다.
 */
export const SPLASH_LONG_LOADING_THRESHOLD_MS: number | null = null;

/**
 * 세션 확인이 즉시 끝나도 스플래쉬를 최소한 이만큼은 띄우는 시간(ms).
 *
 * `null`이면 확인이 끝나는 즉시 넘어간다. 캐시가 살아 있으면 조회가 수십 ms에 끝나 화면이
 * 한 번 번쩍이는데, 그걸 막을지는 정해진 바 없다.
 */
export const SPLASH_MINIMUM_VISIBLE_MS: number | null = null;
