/**
 * 결제수단(B-14) 화면이 요구하는 타입.
 *
 * `types/address.ts`와 같은 원칙이다. 백엔드 응답을 옮긴 것이 아니라 **화면이 필요로 하는 모양**이며,
 * 규격이 나오면 API 계층에서 변환해 이 타입으로 맞춘다.
 *
 * 실제 데이터 원본은 토스페이먼츠 브랜드페이 SDK다(FN-B14-02, 08.26 mock→위젯 전환). 토스가
 * SoT이고 앱은 캐시라, 연동 시 이 타입은 토스 결제수단 응답을 화면용으로 매핑한 결과가 된다.
 * 카드번호·유효기한·CVC는 앱이 절대 보관하지 않는다 — 아래에도 마스킹 표기용 최소 값만 둔다.
 */

/**
 * 등록된 결제수단(카드) 한 건.
 *
 * 카드번호는 마스킹 표기에 필요한 앞 4자리(`bin`)·뒤 4자리(`last4`)만 갖는다. 가운데는 노출하지
 * 않으므로 저장하지 않는다. 실제 마스킹 형식은 토스 실물 응답 확인 후 조정한다(명세 '보류').
 */
export interface PaymentMethod {
  id: string;
  /** 카드명. 시안 예시 '카드의정석 SHOPPING+' · '신한카드 SOL Plan+'. */
  name: string;
  /** 카드번호 앞 4자리(BIN 일부). 마스킹 표기용. */
  bin: string;
  /** 카드번호 뒤 4자리. 마스킹 표기용. */
  last4: string;
  /** 기본결제수단 여부. 계정당 최대 1건이 true. */
  isDefault: boolean;
}
