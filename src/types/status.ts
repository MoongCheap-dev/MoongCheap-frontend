/**
 * 상태 배지·칩의 시각 톤. 공구 상태·주문 상태가 공유한다.
 *
 * 상태값(GB_*·ORD_*)은 기능정의서에서 확정됐지만 각 상태의 **색**은 디자인 미확정이다.
 * 그래서 상태마다 색을 직접 박지 않고 의미 단위의 톤만 부여한다. 실제 색은 배지 컴포넌트가
 * 시맨틱 토큰으로 매핑하며(StatusBadge), 시안이 나오면 그 매핑 한 곳만 고친다.
 */
export type StatusTone =
  | 'brand' // 진행·참여 가능 (모이는 중, 결제완료 등 활성 진입점)
  | 'info' // 처리 진행 중 (배송요청·준비중·배송중처럼 대기 성격)
  | 'success' // 완료·성립 (종료, 배송완료, 구매확정)
  | 'warning' // 사용자 조치 필요 (확인 필요, 대체상품 제안)
  | 'neutral'; // 종결·비활성 (취소 등)

/**
 * 상태 레지스트리 한 항목의 공통 모양. 공구·주문 상태 상수가 이 형태를 따른다.
 *
 * `next`는 상태 전이 그래프의 간선이다. 여기 없는 전이는 정의상 불가능하며, 전이 검증
 * 헬퍼(canTransition)가 이 배열만 참조한다. 백엔드가 상태를 확정 관리하므로 이 그래프는
 * 화면이 다음 동작·표기를 판단하기 위한 프론트의 참조 모델이지 권위 있는 소스가 아니다.
 */
export interface StatusMeta<Code extends string> {
  /** 화면에 노출하는 한글 라벨. 상태정의 시트의 '상태명'을 그대로 따른다. */
  readonly label: string;
  readonly tone: StatusTone;
  /** 종료 상태 여부. 종료 상태는 next가 비어 있다. */
  readonly isTerminal: boolean;
  /** 이 상태에서 전이 가능한 다음 상태들. 종료 상태면 빈 배열. */
  readonly next: readonly Code[];
}
